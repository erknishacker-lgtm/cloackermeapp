function solid(Icon) {
  return function SolidIcon({ size = 16, className, ...rest }) {
    const { weight: _w, strokeWidth: _s, stroke: _st, fill: _f, ...safe } = rest;
    return (
      <Icon
        size={size}
        weight="fill"
        color="currentColor"
        className={className}
        {...safe}
      />
    );
  };
}

